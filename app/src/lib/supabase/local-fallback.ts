import { hasSupabaseEnv } from "./env";

/**
 * 로컬 시드 폴백을 써도 되는가 (BBE-203).
 *
 * ★ 이 함수가 지키는 것은 «운영에서 조용한 시드 노출 0» 이다.
 *
 * `hasSupabaseEnv()` 만으로 갈리면 안 된다. 그 분기는 **로컬에서만 참인 조건이 아니기 때문**이다 —
 * 운영에서 Vercel 환경변수가 빠지거나 오타가 나면 같은 분기가 «운영에서» 돈다. 그러면 사용자 화면에
 * 보드 수·고객사 수·전환율이 전부 시드 값으로 뜨는데 **아무도 오류를 못 본다.**
 * 사용자는 그게 자기 회사 데이터인 줄 안다.
 *
 * 지금 그 자리에서 500 이 나는 것은 그 사고를 «막고 있는» 것이다.
 * 시끄럽게 실패하는 편이 조용히 거짓말하는 것보다 낫다.
 *
 * 경계 이름의 «implicit» 는 「코드에 if 가 적혀 있느냐」가 아니라
 * **「사용자가 그 전환을 알아채지 못하느냐」** 로 읽어야 한다.
 * env 게이트는 코드에는 명시적이지만 사용자에게는 여전히 암묵적이다.
 *
 * 그래서 개발 빌드에서만 연다:
 * ```
 * 운영 빌드 + env 있음 → Supabase   (종전과 동일)
 * 운영 빌드 + env 없음 → 던진다      (종전과 동일 — 이 줄이 경계의 핵심이다)
 * 개발 빌드 + env 없음 → 로컬 시드   (이것만 새로 열린다)
 * 개발 빌드 + env 있음 → Supabase   (종전과 동일)
 * ```
 */
export function canUseLocalSeedFallback(): boolean {
  return process.env.NODE_ENV !== "production" && !hasSupabaseEnv();
}
