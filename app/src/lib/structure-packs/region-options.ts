/**
 * 축약 표기(먼데이 원본)를 정규 항목으로 옮긴다.
 *
 * 먼데이 실데이터를 나중에 가져올 때 셀 값이 이 세트에 맞아야 하므로,
 * 정규화 규칙을 문서가 아니라 코드로 남긴다. 대응이 없으면 `null`.
 */
export function normalizeRegion(label: string): string | null {
  const corrected = REGION_TYPO_FIXES[label] ?? label;
  if (CANONICAL_REGION_SET.has(corrected)) return corrected;
  for (const suffix of ["시", "군", "구"]) {
    if (CANONICAL_REGION_SET.has(corrected + suffix)) return corrected + suffix;
  }
  return null;
}

/** 먼데이 원문 오기 → 정규 명칭. */
const REGION_TYPO_FIXES: Record<string, string> = { 충북_영통군: "충북_영동군" };

const CANONICAL_REGION_SET = new Set(CANONICAL_REGIONS);

/** 팩 옵션 세트 형식(`FieldOption[]`). 먼데이 규약대로 id = label 이고 색은 없다. */
export function regionOptions(): FieldOption[] {
  return CANONICAL_REGIONS.map((label, order) => ({ id: label, label, order }));
}
